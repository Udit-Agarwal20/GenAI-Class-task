import React, { useState } from 'react';
import { ShieldAlert, ShieldCheck, ChevronDown, ChevronUp, AlertCircle, Sparkles, Loader2 } from 'lucide-react';
import type { AuditDetails } from '../lib/api';

interface EvidenceAuditProps {
  audit?: AuditDetails;
  onRunAudit?: () => void;
  auditLoading?: boolean;
}

export const EvidenceAudit: React.FC<EvidenceAuditProps> = ({
  audit,
  onRunAudit,
  auditLoading = false,
}) => {
  const [isOpen, setIsOpen] = useState(false);

  // If audit is not yet run, show user-triggered action bar
  if (!audit) {
    if (!onRunAudit) return null;

    return (
      <div className="audit-panel" style={{ backgroundColor: '#fbfdfc', borderStyle: 'dashed' }}>
        <div
          style={{
            padding: '10px 14px',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            gap: 12,
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: 8, fontSize: '0.82rem', color: 'var(--text-secondary)' }}>
            <Sparkles size={14} color="var(--forest-600)" />
            <span>Verify factual claims against retrieved passages with an independent audit.</span>
          </div>

          <button
            type="button"
            className="ghost-btn"
            style={{
              padding: '5px 12px',
              fontSize: '0.78rem',
              fontWeight: 600,
              backgroundColor: 'var(--mint-surface)',
              color: 'var(--forest-800)',
              borderColor: 'var(--mint-border)',
              display: 'flex',
              alignItems: 'center',
              gap: 6,
            }}
            onClick={onRunAudit}
            disabled={auditLoading}
          >
            {auditLoading ? (
              <>
                <Loader2 size={13} className="loading-spinner" />
                <span>Auditing...</span>
              </>
            ) : (
              <>
                <ShieldCheck size={14} />
                <span>Audit Evidence</span>
              </>
            )}
          </button>
        </div>
      </div>
    );
  }

  const hasInvalid = audit.invalid_labels && audit.invalid_labels.length > 0;

  return (
    <div className="audit-panel">
      <div className="audit-header" onClick={() => setIsOpen(!isOpen)}>
        <div className="audit-title">
          {hasInvalid ? (
            <ShieldAlert size={15} color="#d97706" />
          ) : (
            <ShieldCheck size={15} color="var(--forest-600)" />
          )}
          <span>Automated Evidence Audit</span>
          {audit.used_labels && audit.used_labels.length > 0 && (
            <span
              style={{
                fontSize: '0.72rem',
                color: 'var(--text-muted)',
                marginLeft: 4,
              }}
            >
              ({audit.used_labels.length} citations verified)
            </span>
          )}
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: 6, color: 'var(--text-secondary)' }}>
          <span style={{ fontSize: '0.74rem' }}>{isOpen ? 'Hide review' : 'Inspect audit'}</span>
          {isOpen ? <ChevronUp size={14} /> : <ChevronDown size={14} />}
        </div>
      </div>

      {isOpen && (
        <div>
          <div className="audit-disclaimer">
            Automated preliminary review generated by local Gemma model. This is an algorithmic evaluation comparing proposed claims against retrieved PDF chunks, not a guarantee of absolute correctness.
          </div>

          {hasInvalid && (
            <div
              style={{
                margin: '8px 14px',
                padding: '6px 10px',
                backgroundColor: '#fffbeb',
                border: '1px solid #fde68a',
                borderRadius: 4,
                fontSize: '0.76rem',
                color: '#92400e',
                display: 'flex',
                alignItems: 'center',
                gap: 6,
              }}
            >
              <AlertCircle size={13} />
              <span>
                Citations without matching retrieved passages: {audit.invalid_labels.join(', ')}
              </span>
            </div>
          )}

          <div className="audit-body">
            {audit.text}
          </div>
        </div>
      )}
    </div>
  );
};
